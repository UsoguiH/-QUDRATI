/* Short lessons — what a path node teaches, in three-minute pieces.

   A node used to be one chapter of the book read off cards. Here it is four to six
   short lessons, each one idea, each taught by doing:
     اكتشف — a guess (free: no heart, not counted), then a `see` card that unfolds
             the trick in big numbers, row by row
     جرّب  — `fill`: the trick's one step, completed from tiles
     ثبّت  — `pick` / `tf` / `type` / `pairs` / `order`: quick reps in several shapes
     تحدَّ — `bank`: one real question from js/data/<domain>.js, by id

   An item is an object, or a function of R (LRNG in app.js: R.int, R.pick, R.ar for
   Arabic numerals, R.opts for an answer plus its likely wrong neighbours) that returns
   one — so a replay, or a missed item coming back at the end of the lesson, arrives
   with new numbers instead of an answer to remember.

   Item fields:
     see   { kick, h, rows: ["~slow", "· note", "!result", "plain"], rule, go }
     pick  { q, big, ch: [...], a: "the right choice's text", why: "…" | { "wrong choice": "…" }, ok, free, recall, keep }
     tf    { q, big, a: true|false, why, ok }
     fill  { q, eq: "… _ …", tiles: [...], a: [one per _], why, ok }
     type  { q, big, a: "٢٧٠" | ["٢٧٠", …], unit, keys: ["−"], why, ok }
     pairs { q, p: [[left, right], …] }   — every left and every right distinct
     order { q, big, tiles: [in the right order], why }
     bank  { id, why }
   *x* in any text marks the one number the eye should land on.

   `why` is written for the specific wrong answer where it can be — "you forgot the
   ÷ ٢" teaches; "the answer is ٥٥" does not. `ok` is one line that says why the right
   answer is right, in the words of the rule.

   node tools/validate_learn.js — runs every generator, checks every answer is among
   its choices, every bank question of a node is served exactly once, no Latin digits. */
